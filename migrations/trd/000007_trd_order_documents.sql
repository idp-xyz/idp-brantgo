-- TRD: the export sales contract (S/C) and proforma invoice (PI) of a sales order and their signed
-- copies (WBS S3-15; tactical model TRD-AGG-SalesOrder OrderContractDocument; TRD-INV-020; UL
-- TRD-SalesContractDocument; master data MD-35: 绑定订单修订哈希；签署版本不可变；草稿不能冒充已签署合同).
-- Python has none of this; the design is the only source.
--
-- order.document.generate renders the order's current revision with order-text/0.1.0 from a POL
-- order_document_template revision, numbered by POL before the transaction (number.issue, document
-- type order for an S/C and proforma_invoice for a PI, business reference the order ID), and stores
-- the binding, the bytes and the commit evidence in one row, in the transaction that holds the quote
-- root and the order FOR UPDATE: at most one document of each kind per order revision, for a draft or
-- active order at that revision and hash. An amended order's old documents stay, read only; its new
-- revision gets documents of its own. order.document.record_signed records a signed copy (ours) or a
-- countersigned copy (the customer's) of a document while the order is still at the document's
-- revision: an EVD business file, never the generated bytes themselves, once per kind. Neither moves
-- the order's row version. Nothing here changes or is deleted.

CREATE TABLE brant_trd.sales_order_document (
    tenant_id             text        NOT NULL,
    company_id            text        NOT NULL,
    order_id              text        NOT NULL,
    order_revision        bigint      NOT NULL CHECK (order_revision > 0),
    document_kind         text        NOT NULL CHECK (document_kind IN ('sales_contract', 'proforma_invoice')),
    order_hash            text        NOT NULL CHECK (order_hash ~ '^[0-9a-f]{64}$'),
    number                text        NOT NULL CHECK (number ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$'),
    sequence_kind         text        NOT NULL CHECK (sequence_kind = 'number_sequence'),
    sequence_id           text        NOT NULL,
    sequence_revision     bigint      NOT NULL CHECK (sequence_revision > 0),
    business_ref          text        NOT NULL,
    template_kind         text        NOT NULL CHECK (template_kind = 'order_document_template'),
    template_id           text        NOT NULL,
    template_revision     bigint      NOT NULL CHECK (template_revision > 0),
    template_content_hash text        NOT NULL CHECK (template_content_hash ~ '^[0-9a-f]{64}$'),
    renderer_version      text        NOT NULL CHECK (renderer_version = 'order-text/0.1.0'),
    generated_at          timestamptz NOT NULL,
    file_name             text        NOT NULL,
    mime_type             text        NOT NULL CHECK (mime_type = 'text/plain'),
    content_sha256        text        NOT NULL CHECK (content_sha256 ~ '^[0-9a-f]{64}$'),
    size_bytes            integer     NOT NULL CHECK (size_bytes BETWEEN 1 AND 1048576),
    content               bytea       NOT NULL,
    -- The commit evidence of order.document.generate.
    command               text        NOT NULL CHECK (command = 'order.document.generate'),
    idempotency_key       text        NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,63}$'),
    authority_epoch       bigint      NOT NULL CHECK (authority_epoch > 0),
    control_epoch         bigint      NOT NULL CHECK (control_epoch >= 0),
    generated_by_kind     text        NOT NULL CHECK (generated_by_kind IN ('human', 'ai')),
    generated_by_id       text        NOT NULL,
    committed_at          timestamptz NOT NULL,
    -- The evidence entries as canonical JSON ([{"name": ..., "value": ...}, ...]) and their SHA-256.
    entries               text        NOT NULL CHECK (left(entries, 1) = '['),
    entries_sha256        text        NOT NULL CHECK (entries_sha256 = encode(sha256(convert_to(entries, 'UTF8')), 'hex')),
    PRIMARY KEY (tenant_id, company_id, order_id, order_revision, document_kind),
    FOREIGN KEY (tenant_id, company_id, order_id) REFERENCES brant_trd.sales_order (tenant_id, company_id, order_id),
    -- One number per order and kind, kept by every revision; the file names the revision.
    CHECK (business_ref = order_id),
    CHECK (file_name = number || '-r' || order_revision::text || '.txt'),
    -- The bytes are the bound ones (every read verifies them again).
    CHECK (octet_length(content) = size_bytes AND encode(sha256(content), 'hex') = content_sha256)
);

CREATE TABLE brant_trd.sales_order_document_signature (
    tenant_id        text        NOT NULL,
    company_id       text        NOT NULL,
    order_id         text        NOT NULL,
    order_revision   bigint      NOT NULL,
    document_kind    text        NOT NULL,
    signature_kind   text        NOT NULL CHECK (signature_kind IN ('signed', 'countersigned')),
    -- The EVD business file holding the signed copy, its SHA-256 and MIME type as EVD registered them.
    file_id          text        NOT NULL CHECK (file_id ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,63}$'),
    file_sha256      text        NOT NULL CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
    file_mime_type   text        NOT NULL CHECK (char_length(file_mime_type) BETWEEN 1 AND 255),
    -- The document it is a copy of, restated: never the generated, unsigned bytes.
    document_sha256  text        NOT NULL CHECK (document_sha256 ~ '^[0-9a-f]{64}$'),
    order_hash       text        NOT NULL CHECK (order_hash ~ '^[0-9a-f]{64}$'),
    idempotency_key  text        NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9][A-Za-z0-9._:-]{0,63}$'),
    recorded_by_kind text        NOT NULL CHECK (recorded_by_kind = 'human'),
    recorded_by_id   text        NOT NULL,
    record_epoch     bigint      NOT NULL CHECK (record_epoch > 0),
    recorded_at      timestamptz NOT NULL,
    evidence         text        NOT NULL CHECK (left(evidence, 1) = '['),
    PRIMARY KEY (tenant_id, company_id, order_id, order_revision, document_kind, signature_kind),
    FOREIGN KEY (tenant_id, company_id, order_id, order_revision, document_kind)
        REFERENCES brant_trd.sales_order_document (tenant_id, company_id, order_id, order_revision, document_kind),
    CHECK (file_sha256 <> document_sha256)
);

-- A document is inserted for a draft or active order at the revision and hash it binds. Never
-- changed or deleted.
CREATE FUNCTION brant_trd.guard_sales_order_document() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'brant_trd.sales_order_document: order documents never change' USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM brant_trd.sales_order o WHERE o.tenant_id = NEW.tenant_id AND o.company_id = NEW.company_id
            AND o.order_id = NEW.order_id AND o.status IN ('draft', 'active') AND o.order_revision = NEW.order_revision
            AND o.order_hash = NEW.order_hash) THEN
        RAISE EXCEPTION 'brant_trd.sales_order_document: a document binds the current revision of a draft or active order'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER sales_order_document_guard BEFORE INSERT OR UPDATE OR DELETE ON brant_trd.sales_order_document
    FOR EACH ROW EXECUTE FUNCTION brant_trd.guard_sales_order_document();

-- A signed copy is inserted for a document of the order's current revision, other than its bytes.
-- Never changed or deleted.
CREATE FUNCTION brant_trd.guard_sales_order_document_signature() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'brant_trd.sales_order_document_signature: signed copies never change'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM brant_trd.sales_order_document d
            JOIN brant_trd.sales_order o ON o.tenant_id = d.tenant_id AND o.company_id = d.company_id AND o.order_id = d.order_id
            WHERE d.tenant_id = NEW.tenant_id AND d.company_id = NEW.company_id AND d.order_id = NEW.order_id
                AND d.order_revision = NEW.order_revision AND d.document_kind = NEW.document_kind AND d.order_hash = NEW.order_hash
                AND d.content_sha256 = NEW.document_sha256 AND o.order_revision = d.order_revision AND o.order_hash = d.order_hash) THEN
        RAISE EXCEPTION 'brant_trd.sales_order_document_signature: a signed copy is of a document of the order''s current revision'
            USING ERRCODE = 'integrity_constraint_violation';
    END IF;
    RETURN NEW;
END
$$;
CREATE TRIGGER sales_order_document_signature_guard BEFORE INSERT OR UPDATE OR DELETE ON brant_trd.sales_order_document_signature
    FOR EACH ROW EXECUTE FUNCTION brant_trd.guard_sales_order_document_signature();

