// Package shipmentdocumentset holds the rules of FUL's ShipmentDocumentSet aggregate (tactical model
// FUL-AGG-ShipmentDocumentSet "单证套根 CAS；版本只追加，签发后不可变"; SM-FUL-DOCUMENT; FUL-INV-004; UL
// FUL-ShipmentDocumentSet "单证草稿不等于已签发；附件存在不等于真实性已核实"; MD-39; baseline BT12, CN-AT17,
// INT-05; WBS S5-08): the versions of a shipment's commercial invoice and packing list, which FUL
// renders with shipment-text/0.1.0, and of the records of its external bill of lading and
// certificate of origin; the item-by-item reconciliation of the current versions with the shipment's
// facts and with each other; their issue; and the signed copies of issued versions. The package knows
// no database: the application gives it what FUL stores and what POL, TRD, PTY and EVD said.
package shipmentdocumentset

import (
	"slices"
	"strconv"
	"time"

	"go.idp.xyz/idp-brant/internal/contexts/ful/internal/domain/shipment"
	"go.idp.xyz/idp-brant/internal/kernel"
)

// Document kinds, states of a version (SM-FUL-DOCUMENT) and the renderer.
const (
	KindCommercialInvoice   = "commercial_invoice"
	KindPackingList         = "packing_list"
	KindBillOfLading        = "bill_of_lading"
	KindCertificateOfOrigin = "certificate_of_origin"

	Draft      = "draft"
	Issued     = "issued"
	Superseded = "superseded"

	RendererVersion = "shipment-text/0.1.0"
	LanguageEn      = "en"
	LanguageZhCN    = "zh-CN"
	MimeText        = "text/plain"

	// The POL number sequence document types of the rendered kinds and the POL kinds a rendering
	// names.
	DocumentTypeInvoice          = "invoice"
	DocumentTypePackingList      = "packing_list"
	KindShipmentDocumentTemplate = "shipment_document_template"
	KindNumberSequence           = "number_sequence"
	KindCompanyProfile           = "company_profile"

	MaxDocumentBytes = 1 << 20
)

// Kinds returns the document kinds in their order (S5-16 adds the insurance policy record,
// insurance.go).
func Kinds() []string {
	return []string{KindCommercialInvoice, KindPackingList, KindBillOfLading, KindCertificateOfOrigin, KindInsurancePolicy}
}

// Rendered reports whether FUL renders documents of kind.
func Rendered(kind string) bool { return kind == KindCommercialInvoice || kind == KindPackingList }

// DocumentType returns the POL number sequence document type of rendered kind.
func DocumentType(kind string) string {
	if kind == KindCommercialInvoice {
		return DocumentTypeInvoice
	}
	return DocumentTypePackingList
}

// Act is who did something, under which authority epoch, when.
type Act = shipment.Act

// Entry is one named value of commit evidence or of a version's sources.
type Entry = shipment.Entry

// Ref names a POL configuration revision.
type Ref struct {
	Kind     string
	ID       string
	Revision int64
}

// String is the reference as evidence names it: kind:id@revision.
func (r Ref) String() string { return r.Kind + ":" + r.ID + "@" + strconv.FormatInt(r.Revision, 10) }

// Rendition is one language of a rendered version: the template it was rendered from and the file.
// Content is nil when the store did not load the bytes.
type Rendition struct {
	Language     string
	Template     Ref
	TemplateHash string
	FileName     string
	MimeType     string
	SHA256       string
	Size         int
	Content      []byte
}

// Signature is the signed or stamped copy of one language of an issued version: an EVD file, never
// the generated bytes.
type Signature struct {
	Language       string
	FileID         string
	FileSHA256     string
	MimeType       string
	DocumentSHA256 string
	Evidence       []string
	IdempotencyKey string
	Recorded       Act
}

// File is an EVD business file as EVD shows it: its ID, SHA-256 and MIME type.
type File struct {
	ID       string
	SHA256   string
	MimeType string
}

// Document is one version of a kind. A rendered version has its content, number, POL revisions and
// renditions; a record of an external document has its record and EVD file. Sources name what it
// was prepared from (traceability); Entries are its commit evidence, sealed as EntriesJSON with
// EntriesSHA256.
type Document struct {
	Kind            string
	Version         int64
	Status          string
	Number          string
	SetVersion      int64
	Sequence        *Ref
	SequenceHash    string
	Seller          *Ref
	SellerHash      string
	RendererVersion string
	Content         *Content
	Record          *Record
	ContentJSON     string
	ContentSHA256   string
	File            *File
	Sources         []Entry
	Renditions      []Rendition
	Evidence        []string
	IdempotencyKey  string
	Prepared        Act
	Entries         []Entry
	EntriesJSON     string
	EntriesSHA256   string
	IssueSeq        int64
	IssuedAt        time.Time
	SupersededAt    time.Time
	Signatures      []Signature
}

// Rendition returns the rendition of language, or nil.
func (d *Document) Rendition(language string) *Rendition {
	for i := range d.Renditions {
		if d.Renditions[i].Language == language {
			return &d.Renditions[i]
		}
	}
	return nil
}

// OrderBinding is the order a shipment binds: at an order revision and its order hash.
type OrderBinding = shipment.OrderBinding

// Set is the aggregate root: a shipment's documents. RowVersion counts its prepared versions and its
// issues (DocumentCount + IssueCount); a signed copy does not move it.
type Set struct {
	ID            string
	ShipmentID    string
	Order         OrderBinding
	RowVersion    int64
	DocumentCount int64
	IssueCount    int64
	OwnerActor    string
	OwnerTeam     string
	Created       Act
	Documents     []*Document // every version, kind order then version
	Issues        []*Issue
}

// Versions returns the versions of kind, oldest first.
func (s *Set) Versions(kind string) []*Document {
	var out []*Document
	for _, d := range s.Documents {
		if d.Kind == kind {
			out = append(out, d)
		}
	}
	return out
}

// Document returns version version of kind, or nil.
func (s *Set) Document(kind string, version int64) *Document {
	for _, d := range s.Documents {
		if d.Kind == kind && d.Version == version {
			return d
		}
	}
	return nil
}

// Current returns the version of kind the set stands on: its draft, else its issued version, else
// nil.
func (s *Set) Current(kind string) *Document {
	var issued *Document
	for _, d := range s.Documents {
		if d.Kind != kind {
			continue
		}
		switch d.Status {
		case Draft:
			return d
		case Issued:
			issued = d
		}
	}
	return issued
}

// IssuedBillOfLading returns the issued version of the bill of lading record, or nil: what a
// documents release is recorded on (document_release.record, S5-07).
func (s *Set) IssuedBillOfLading() *Document {
	for _, d := range s.Documents {
		if d.Kind == KindBillOfLading && d.Status == Issued {
			return d
		}
	}
	return nil
}

// Drafts returns the drafts of the set in kind order.
func (s *Set) Drafts() []*Document {
	var out []*Document
	for _, k := range Kinds() {
		if d := s.Current(k); d != nil && d.Status == Draft {
			out = append(out, d)
		}
	}
	return out
}

// sortDocuments keeps the versions in kind order, then version.
func (s *Set) sortDocuments() {
	order := Kinds()
	slices.SortStableFunc(s.Documents, func(a, b *Document) int {
		if a.Kind != b.Kind {
			return slices.Index(order, a.Kind) - slices.Index(order, b.Kind)
		}
		return int(a.Version - b.Version)
	})
}

// Open checks a prepare against the set: another row version than expected is VERSION_CONFLICT,
// another shipment than the set's INVALID_KNOWN_VALUE.
func (s *Set) Open(expected int64, shipmentID string) error {
	if s.RowVersion != expected {
		return Reject(kernel.CodeVersionConflict, "/args/expected_version", "")
	}
	if s.ShipmentID != shipmentID {
		return Reject(kernel.CodeInvalidKnownValue, "/args/shipment_id", "The document set is of shipment "+s.ShipmentID)
	}
	return nil
}

// NewSet opens set id of shipment sh for its first version, prepared by act (shipment_document.prepare
// with expected_version 0).
func NewSet(id string, sh *shipment.Shipment, team string, act Act) *Set {
	act.At = kernel.Instant(act.At)
	return &Set{ID: id, ShipmentID: sh.ID, Order: sh.Order, OwnerActor: act.By.ID, OwnerTeam: team, Created: act}
}

// Add appends prepared version d of its kind (SM-FUL-DOCUMENT: created as a draft; the kind's draft
// before it is superseded, its issued version stays) and moves the set's row version. It returns the
// draft superseded, or nil.
func (s *Set) Add(d *Document) *Document {
	var superseded *Document
	if c := s.Current(d.Kind); c != nil && c.Status == Draft {
		c.Status, c.SupersededAt, superseded = Superseded, d.Prepared.At, c
	}
	s.RowVersion, s.DocumentCount = s.RowVersion+1, s.DocumentCount+1
	d.SetVersion, d.Status = s.RowVersion, Draft
	s.Documents = append(s.Documents, d)
	s.sortDocuments()
	return superseded
}

// NextVersion is the version a new document of kind gets.
func (s *Set) NextVersion(kind string) int64 {
	var v int64
	for _, d := range s.Documents {
		if d.Kind == kind && d.Version > v {
			v = d.Version
		}
	}
	return v + 1
}

// Readable refuses the first of ids that found, the sources the actor reads, does not hold
// (REFERENCE_INVALID at path/<index>).
func Readable(ids []string, found map[string]bool, path string) error {
	return shipment.Readable(ids, found, path)
}
